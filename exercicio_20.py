# exercício 20 - dia da semana
# objetivo: resolver dia da semana conforme o enunciado

# entrada
dia = int(input("Dia (1 a 7): "))
# decisão e saída
if dia == 1:
    print("Domingo")
elif dia == 2:
    print("Segunda-feira")
elif dia == 3:
    print("Terça-feira")
elif dia == 4:
    print("Quarta-feira")
elif dia == 5:
    print("Quinta-feira")
elif dia == 6:
    print("Sexta-feira")
elif dia == 7:
    print("Sábado")
else:
    print("Dia inválido")
